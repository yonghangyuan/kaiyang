# 行政级别权重: 匹配优先级 = (名称长度降序, 具体度降序)。
# 同长度时县级最具体 → 权重最高: county > city > province/region/sea。
# "西藏吉隆"标题里"吉隆"(县)压过"西藏"(省), 坐标落到灾害实际发生地。
_LEVEL = {"county": 4, "city": 3, "province": 2, "sea": 2, "region": 2}
_PLACE_LEVEL: dict[str, str] = {}

def _init_levels() -> None:
    provinces = {"北京", "上海", "天津", "重庆", "西藏", "新疆", "黑龙江", "吉林", "辽宁",
                 "河北", "山西", "内蒙古", "甘肃", "青海", "宁夏", "山东", "江苏", "浙江",
                 "安徽", "福建", "江西", "河南", "湖北", "湖南", "广东", "海南", "广西",
                 "四川", "贵州", "云南", "中国台湾", "台湾", "中国香港", "香港", "中国澳门", "澳门"}
    seas = {"台湾海峡", "渤海", "黄海", "东海", "南海"}
    for name in CHINA_PLACES:
        if name in provinces or name in seas:
            _PLACE_LEVEL[name] = "sea" if name in seas else "province"
        else:
            _PLACE_LEVEL[name] = "county" if len(name) <= 2 else "city"

_init_levels()

_SORTED_PLACES = sorted(
    CHINA_PLACES,
    key=lambda n: (-len(n), -_LEVEL[_PLACE_LEVEL[n]]),
)


def find_china_place(text: str) -> tuple[str, float, float, str, str] | None:
    """在文本中查找中国地名, 返回 (name, lat, lng, iso, 上级)。

    匹配策略: 长名优先。返回 None 表示不含已知中国地名。
    """
    if not text:
        return None
    t = text.lower()
    for name in _SORTED_PLACES:
        if name in t:
            lat, lng, iso, parent = CHINA_PLACES[name]
            return (name, lat, lng, iso, parent)
    return None
